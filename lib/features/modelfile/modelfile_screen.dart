  @override
  void dispose() {
    _modelNameController.dispose();
    _systemPromptController.dispose();
    _stopTokenController.dispose();
    super.dispose();
  }

  String _generateModelfileContent(String baseModel) {
    final buffer = StringBuffer();
    buffer.writeln('# Modelfile generated by Ollama GUI');
    buffer.writeln('FROM $baseModel\n');

    final system = _systemPromptController.text.trim();
    if (system.isNotEmpty) {
      buffer.writeln('# System Prompt');
      buffer.writeln('SYSTEM """');
      buffer.writeln(system);
      buffer.writeln('"""\n');
    }

    buffer.writeln('# Inference Parameters');
    buffer.writeln('PARAMETER temperature ${_temperature.toStringAsFixed(2)}');
    buffer.writeln('PARAMETER top_p ${_topP.toStringAsFixed(2)}');
    buffer.writeln('PARAMETER num_ctx $_numCtx');

    final stopToken = _stopTokenController.text.trim();
    if (stopToken.isNotEmpty) {
      buffer.writeln('PARAMETER stop "$stopToken"');
    }

    return buffer.toString();
  }

  Future<void> _buildModel(String modelfile) async {
    final targetName = _modelNameController.text.trim();
    if (targetName.isEmpty) return;

    setState(() {
      _isBuilding = true;
      _buildSuccess = false;
      _buildLogs.clear();
      _buildLogs.add('Starting build for "$targetName"...');
    });

    try {
      final client = ref.read(ollamaClientProvider);
      await client.createModel(
        name: targetName,
        modelfile: modelfile,
        onProgress: (status) {
          if (!mounted) return;
          setState(() {
            _buildLogs.add(status);
          });
        },
      );

      if (mounted) {
        setState(() {
          _isBuilding = false;
          _buildSuccess = true;
          _buildLogs.add('✓ Successfully created model "$targetName"');
        });
        ref.read(modelsNotifierProvider.notifier).refresh();
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _isBuilding = false;
          _buildLogs.add('✕ Build failed: $e');
        });
      }
    }
  }

  Future<void> _startChatWithCreatedModel() async {
    final targetName = _modelNameController.text.trim();
    final db = ref.read(appDatabaseProvider);
    final convId = await db.insertConversation(
      ConversationsCompanion(
        title: Value('Chat with $targetName'),
        model: Value(targetName),
        createdAt: Value(DateTime.now()),
        updatedAt: Value(DateTime.now()),
      ),
    );

    ref.read(selectedModelProvider.notifier).state = targetName;
    ref.read(activeConversationProvider.notifier).state = convId;
    if (mounted) {
      context.go('/chat?id=$convId');
    }
  }

